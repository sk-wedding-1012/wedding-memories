# Generates sm/ (grid tiles), thumbs/ (first view when enlarged), large/ (enlarged + saving) and photos.js from photos/.
# Usage: powershell -ExecutionPolicy Bypass -File tools\build-photos.ps1
# - The scene of a photo is its folder name: photos/<scene id>/xxx.jpg (photos directly in photos/ = no scene).
# - sm/, thumbs/ and large/ mirror photos/. Existing files are kept; ones whose original is gone are deleted.
# - photos/ (originals) stays on this PC only (.gitignore); the site uses sm/, thumbs/ and large/.

Add-Type -AssemblyName System.Drawing
$root   = Split-Path -Parent $PSScriptRoot
$photos = Join-Path $root "photos"
$list   = Join-Path $root "photos.js"
$utf8   = New-Object System.Text.UTF8Encoding $false
$jpeg   = [System.Drawing.Imaging.ImageCodecInfo]::GetImageEncoders() | Where-Object MimeType -eq "image/jpeg"
$targets = @(
  @{ Dir = Join-Path $root "sm";     MaxSide = 480;  Quality = 78 },
  @{ Dir = Join-Path $root "thumbs"; MaxSide = 1000; Quality = 82 },
  @{ Dir = Join-Path $root "large";  MaxSide = 2400; Quality = 85 }
)

function RelPath($base, $full) { $full.Substring($base.Length + 1).Replace('\', '/') }

# Natural sort (name_2 before name_10)
$files = Get-ChildItem $photos -File -Recurse | Where-Object { $_.Extension -match '^\.(jpe?g|png|webp)$' } |
  Sort-Object { [regex]::Replace((RelPath $photos $_.FullName), '\d+', { param($x) $x.Value.PadLeft(12, '0') }) }

foreach ($t in $targets) {
  New-Item -ItemType Directory -Force $t.Dir | Out-Null
  $enc = New-Object System.Drawing.Imaging.EncoderParameters 1
  $enc.Param[0] = New-Object System.Drawing.Imaging.EncoderParameter ([System.Drawing.Imaging.Encoder]::Quality), ([long]$t.Quality)
  $made = 0
  foreach ($f in $files) {
    $out = Join-Path $t.Dir (RelPath $photos $f.FullName)
    if (Test-Path -LiteralPath $out) { continue }
    New-Item -ItemType Directory -Force (Split-Path -Parent $out) | Out-Null
    $img = [System.Drawing.Image]::FromFile($f.FullName)
    try {
      if ($img.PropertyIdList -contains 274) {
        switch ([int]$img.GetPropertyItem(274).Value[0]) {
          3 { $img.RotateFlip("Rotate180FlipNone") }
          6 { $img.RotateFlip("Rotate90FlipNone") }
          8 { $img.RotateFlip("Rotate270FlipNone") }
        }
      }
      $s = [Math]::Min(1.0, $t.MaxSide / [Math]::Max($img.Width, $img.Height))
      $w = [int]($img.Width * $s); $h = [int]($img.Height * $s)
      $bmp = New-Object System.Drawing.Bitmap $w, $h
      $g = [System.Drawing.Graphics]::FromImage($bmp)
      $g.InterpolationMode = "HighQualityBicubic"
      $g.DrawImage($img, 0, 0, $w, $h)
      $g.Dispose()
      $bmp.Save($out, $jpeg, $enc)
      $bmp.Dispose()
      $made++
    } finally { $img.Dispose() }
  }

  # Remove files whose original was moved or deleted, then empty folders
  $removed = 0
  foreach ($x in Get-ChildItem $t.Dir -File -Recurse | Where-Object Name -ne ".gitkeep") {
    if (-not (Test-Path -LiteralPath (Join-Path $photos (RelPath $t.Dir $x.FullName)))) { Remove-Item -LiteralPath $x.FullName; $removed++ }
  }
  Get-ChildItem $t.Dir -Directory -Recurse | Sort-Object { $_.FullName.Length } -Descending |
    Where-Object { -not (Get-ChildItem $_.FullName -Force) } | Remove-Item
  Write-Host "$(Split-Path -Leaf $t.Dir): new $made  removed $removed"
}

$lines = foreach ($f in $files) {
  $rel = RelPath $photos $f.FullName
  $scene = if ($rel.Contains('/')) { $rel.Split('/')[0] } else { "" }
  '  {"file":"' + $rel.Replace('"', '\"') + '", "scene":"' + $scene + '"}'
}
$js = "// Generated by tools/build-photos.ps1 - do not edit. Move photos between photos/<scene>/ folders and re-run instead.`n" +
      "window.PHOTO_LIST = [`n" + ($lines -join ",`n") + "`n];`n"
[IO.File]::WriteAllText($list, $js, $utf8)

$byScene = $files | Group-Object { $r = RelPath $photos $_.FullName; if ($r.Contains('/')) { $r.Split('/')[0] } else { "(none)" } } |
  ForEach-Object { "$($_.Name):$($_.Count)" }
Write-Host "photos: $($files.Count)"
Write-Host ($byScene -join "  ")
